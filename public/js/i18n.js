let mode = 'system';
let locale = detectSystemLocale();

export function normalizeLocale(value) {
  if (SUPPORTED.has(value)) return value;
  return 'system';
}

export function detectSystemLocale() {
  const values = navigator.languages?.length ? navigator.languages : [navigator.language];
  return values.some((value) => String(value || '').toLowerCase().startsWith('zh')) ? 'zh-CN' : 'en-US';
}

export function setLocale(value, { announce = true } = {}) {
  mode = normalizeLocale(value);
  locale = mode === 'system' ? detectSystemLocale() : mode;
  document.documentElement.lang = locale;
  if (announce) window.dispatchEvent(new CustomEvent('a2s:locale', { detail: { mode, locale } }));
  return locale;
}

export function getLocale() { return locale; }
export function getLocaleMode() { return mode; }
export function isEnglish() { return locale === 'en-US'; }

export function translateUi(value) {
  if (!isEnglish() || typeof value !== 'string' || value === '') return value;
  const exact = EN[value];
  if (exact !== undefined) return exact;
  for (const [pattern, replacement] of PATTERNS) {
    if (pattern.test(value)) return value.replace(pattern, replacement);
  }
  return value;
}

export function translateHtml(value) {
  if (!isEnglish() || typeof value !== 'string' || value === '') return value;
  let output = value;
  for (const [source, translated] of Object.entries(EN).sort((a, b) => b[0].length - a[0].length)) {
    if (source && output.includes(source)) output = output.split(source).join(translated);
  }
  return output;
}

export function ui(key, fallback, values = {}) {
  const source = locale === 'en-US' ? (EN[key] ?? fallback ?? key) : (fallback ?? key);
  return String(source).replace(/\{(\w+)\}/g, (whole, name) =>
    (Object.hasOwn(values, name) ? String(values[name]) : whole));
}

export function localeName(value) {
  return {
    system: translateUi('自动（跟随系统）'),
    'zh-CN': translateUi('简体中文'),
    'en-US': 'English',
  }[normalizeLocale(value)];
}
